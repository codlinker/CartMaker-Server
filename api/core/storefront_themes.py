def resolve_company_storefront_theme(company_category_name: str = "", dominant_parent_category: str = "") -> Dict[str, Any]:
    """
    Determina la personalidad visual interactiva de la vitrina pública según
    la categoría de la compañía o la categoría dominante de su inventario.
    """
    raw = f"{company_category_name or ''} {dominant_parent_category or ''}"
    norm_txt = _norm(raw)

    keyword_mapping = [
        (("tecnolog", "electron", "celular", "comput", "gaming", "electrodomest"), "tech_cyber"),
        (("salud", "bellez", "farmac", "cosmet", "maquill", "perfum", "skincare", "spa", "barber"), "beauty_editorial"),
        (("aliment", "bebid", "restauran", "comid", "bodegon", "supermercad", "panader", "licor", "cafe", "gastron"), "gourmet_bistro"),
        (("moda", "ropa", "calzad", "zapat", "joyer", "boutique", "vestid", "accesorio"), "fashion_runway"),
        (("carro", "moto", "vehicul", "repuest", "automot", "caucho", "lubricant", "taller"), "auto_telemetry"),
        (("ferreter", "construc", "herramient", "plomer", "electric", "pintur", "industrial"), "industrial_pro"),
        (("hogar", "muebl", "jardin", "decorac", "colchon", "cocina", "iluminac"), "nordic_architect"),
        (("deport", "fitness", "gimnasi", "ciclism", "camping", "outdoor", "suplement"), "kinetic_sport"),
        (("bebe", "maternid", "infantil", "panal", "escolar"), "pastel_cloud"),
        (("mascot", "veterinar", "perro", "gato", "pet"), "pet_nature"),
        (("jueg", "juguet", "coleccion", "anime", "hobby"), "arcade_pop"),
        (("instrument", "music", "guitar", "audio", "piano"), "acoustic_stage"),
        (("papeler", "oficin", "libro", "librer", "arte"), "atelier_press"),
    ]

    for keywords, theme_key in keyword_mapping:
        if any(k in norm_txt for k in keywords):
            return dict(STOREFRONT_THEMES[theme_key])

    return dict(STOREFRONT_THEMES["cartmaker_signature"])
